numbers = list(range(1,10))
print(numbers)

for i in numbers:
    if i == 1:
        print(f"{i}st")
    elif i == 2:
        print(f"{i}nd")
    elif i == 3:
        print(f"{i}rd")
    elif i == 4:
        print(f"{i}th")
    elif i == 5:
        print(f"{i}th")
    elif i == 6:
        print(f"{i}th")
    elif i == 7:
        print(f"{i}th")
    elif i == 8:
        print(f"{i}th")
    else:
        print(f"{i}th")
